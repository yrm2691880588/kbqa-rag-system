"""闲聊（寒暄）识别：把问候/致谢/告别/自我介绍类话语挡在 RAG 检索之前。

背景：若不识别，用户说"你好"也会被当作知识库问题去向量检索，既浪费请求，
又常因检索不到资料而回一句生硬的"没找到相关资料"，体验很差。

设计：
- 采用"关键词剥离 + 剩余长度判断"：先把句子里的寒暄词去掉，若剩下没什么实质
  内容（<= 2 个字符，可能只剩"啊/呀/呢"之类语气词），判定为纯寒暄；
- 若剥离后还剩较多文字（如"你好，净化器多少钱？"去掉"你好"还剩半句真问题），
  不拦截，照常走知识库检索——避免误伤真实提问。
"""

import re

# 常见寒暄/身份类话语（按长度降序匹配，长词优先，避免子串误伤）
_SMALLTALK_WORDS: list[str] = [
    "你好", "您好", "哈喽", "hello", "hi", "嗨", "hey", "在吗", "在不在",
    "早上好", "上午好", "中午好", "下午好", "晚上好", "晚安",
    "再见", "拜拜", "bye",
    "谢谢", "感谢", "多谢", "辛苦了", "辛苦", "麻烦你了",
    "你是谁", "你叫什么名字", "你叫什么", "你叫什么呀", "你叫啥",
    "介绍一下你自己", "介绍下你自己", "自我介绍一下", "自我介绍",
    "你能做什么", "你能干什么", "你会什么", "你可以做什么", "有什么功能",
    "你都能干什么", "你能帮我什么", "能做什么",
]

# 剥离用：去掉空白与常见标点，便于比较剩余内容
_STRIP_RE = re.compile(r"[\s，。！？、,.!?~～;；:'\"“”‘’()（）…·\-]+")

# 剥离后剩余的"语气词/无意义字"，允许残留
_TRIVIAL_TAIL = set("啊呀哦喔嗯呢吧嘛哈嘿哟了唉哎")

_MSG_GREET = (
    "您好！我是本企业知识库问答助手，可以帮您回答商品资料相关的问题"
    "（如产品参数、功能、价格、使用方法等）。请直接告诉我您想了解什么，"
    "我会从知识库中查找并给出带引用出处的回答。"
)
_MSG_THANKS = "不客气！有什么想了解的随时问我。"
_MSG_BYE = "再见，期待下次为您服务！"
_MSG_WHOAMI = (
    "我是知识库问答助手，专门回答本企业商品资料的问题，比如产品规格、"
    "使用说明、常见问题等。您想问什么？我会从知识库里找到答案，并标注引用来源。"
)

# 身份/能力类询问词条（**必须是"你/自己"作主语的完整短语**，禁止裸词如"介绍""有什么功能"
# "能做什么"——否则"净化器有什么功能""介绍一下星耀A8"这类产品真问题会被误伤拦截）
_WHOAMI_WORDS: tuple[str, ...] = (
    # 问"你是谁/叫什么"
    "你是谁", "你叫什么名字", "你叫什么", "你叫什么呀", "你叫啥",
    "你是做什么的", "你是干什么的",
    # 问"你能做什么/会什么"
    "你能做什么", "你能干什么", "你可以做什么", "你能做些什么",
    "你能帮我什么", "你能回答什么", "你会什么", "你会做什么",
    # 问"你有什么功能/都会什么"
    "你有什么功能", "你有什么能力", "你都会做什么", "你都能做什么",
    "你都能干什么", "你都可以做什么",
    # 自我介绍类
    "介绍一下你自己", "介绍下你自己", "介绍你自己", "自我介绍一下", "自我介绍",
)
_GREET_WORDS = ("你好", "您好", "哈喽", "hello", "hi", "嗨", "hey", "在吗", "在不在", "早", "中午好", "下午好", "晚上好", "晚安")
_THANKS_WORDS = ("谢谢", "感谢", "多谢", "辛苦", "麻烦")
_BYE_WORDS = ("再见", "拜拜", "bye")


def detect_smalltalk(question: str) -> str | None:
    """判断是否纯寒暄/自我介绍；是则返回应回复的文案，否则返回 None（走正常 RAG）。

    Args:
        question: 用户输入原文。

    Returns:
        命中寒暄时返回礼貌回复文案；未命中返回 None。
    """
    if not question or not question.strip():
        return None

    # 归一化：小写 + 去空白标点，只留有效文字
    q = _STRIP_RE.sub("", question).strip().lower()
    if not q:
        return None

    # 身份/能力类整句判断：把身份短语从句子中剥离（长词优先），
    # 若剩余为空或只剩语气词 → 是纯身份询问（回身份文案）。
    # 注意：不能"包含即命中"，否则"净化器有什么功能""你能做什么产品评测"这类
    # 产品真问题会因含身份子串被误伤——必须剥离后看剩余有没有实质内容。
    if len(q) <= 16:
        rest = q
        for w in sorted(_WHOAMI_WORDS, key=len, reverse=True):
            rest = rest.replace(w, "")
        if not rest or all(ch in _TRIVIAL_TAIL for ch in rest):
            return _MSG_WHOAMI

    # 关键词剥离法：把寒暄词全部剥掉，看剩什么
    rest = q
    hit_any = False
    for w in sorted(_SMALLTALK_WORDS, key=len, reverse=True):
        if w in rest:
            rest = rest.replace(w, "")
            hit_any = True

    # 没命中任何寒暄词 → 不是闲聊
    if not hit_any:
        return None

    # 剩余部分若只是语气词/空 → 纯寒暄；还有实质内容 → 可能夹带真问题，不拦截
    if all(ch in _TRIVIAL_TAIL for ch in rest) and len(rest) <= 3:
        # 细分文案：致谢/告别/问候
        if any(w in q for w in _THANKS_WORDS):
            return _MSG_THANKS
        if any(w in q for w in _BYE_WORDS):
            return _MSG_BYE
        return _MSG_GREET

    return None
