"""财经领域模块。

## 这个领域的特殊性：合规是硬约束

财经问答与电商有一个本质差别：**说错话会有真实后果**。

- 电商答错一个参数 → 用户买错东西，退货了事
- 财经给出投资建议 → 用户可能真的亏钱，且平台有法律风险

所以这里 `forbidden` 写得比电商具体得多，不是"不要违规"这种空话，
而是逐条列出「绝对不能出现的表述」。这也是验证「领域禁令配置」
是否真的有价值的最好例子。

## 与电商的隔离验证

本模块建立后，可以用它检验领域抽象是否彻底：
`DOMAIN=finance` 启动时应完全找不到「商品」「S10」这类电商词，
`DOMAIN=ecommerce` 启动时也不应出现「市盈率」「K 线」。
"""

from __future__ import annotations

from app.domain.base import DomainSpec

# ---------------------------------------------------------------------------
# 意图词表
# ---------------------------------------------------------------------------
# 财经场景下用户想要"清单"的说法，与电商（有哪些商品）完全不同。

OPEN_INTENT_KEYWORDS: tuple[str, ...] = (
    # 要一份标的清单
    "有哪些股票", "有什么股票", "股票列表", "股票有哪些",
    "有哪些基金", "有什么基金", "基金列表", "基金有哪些",
    "有哪些产品", "有哪些标的", "投资标的", "可选标的",
    "全部股票", "所有股票", "全部基金", "所有基金",
    # 要一份数据/报告清单
    "有哪些数据", "有什么数据", "数据列表", "指标有哪些",
    "有哪些指标", "有哪些报告", "报告列表",
    # 泛化的"介绍/说说"
    "介绍一下", "介绍下", "介绍一下产品", "介绍下产品",
    "你能介绍", "给我介绍", "给我说说", "你们有什么", "你们提供什么",
)

# 命中列举意图后，若出现下列词，说明用户在问**具体标的或具体指标**，
# 应走检索而不是列清单。
# 例：「介绍一下招商银行」含"介绍一下"（列举词）但"招商银行"是具体标的 → 走 RAG。
SPECIFIC_HINTS: tuple[str, ...] = (
    # 具体标的名称（示例数据中的虚构公司 + 常见类型词）
    "海联银行", "海联", "启明科技", "启明", "长风能源", "长风",
    # 标的类型词（出现即代表问的是某一类具体标的）
    "银行股", "科技股", "能源股", "蓝筹", "成长股", "指数", "ETF",
    # 财务指标（表明用户问的是具体数值，不是要清单）
    "市盈率", "市净率", "净利润", "营业收入", "营收", "毛利率",
    "净资产收益率", "ROE", "资产负债率", "现金流", "分红", "股息",
    # 交易与行情概念
    "股价", "涨跌", "涨幅", "跌幅", "k线", "K线", "成交量", "换手率",
    "市值", "估值", "目标价", "评级",
    # 财报与时间
    "年报", "季报", "半年报", "财报", "同比增长", "环比",
)

# ---------------------------------------------------------------------------
# 领域描述
# ---------------------------------------------------------------------------

spec = DomainSpec(
    name="finance",
    display_name="财经",
    persona="你是财经数据知识库问答助手",
    # 受众是投资者与从业者 —— 措辞要专业，但仍需解释术语
    audience="投资者与金融从业者",
    # 合规禁令：这是本领域最关键的配置，必须具体到"哪些话不能说"
    forbidden=(
        "不要预测股价涨跌、不要判断买卖时机、不要给出目标价",
        "不要推荐具体标的的买入或卖出，不要使用「建议买入」「可以加仓」这类表述",
        "不要承诺任何收益率，不要暗示「稳赚」「保本」「无风险」",
        "引用财务数据时必须注明来源文档与报告期，不得把不同期间的数据混用",
        "涉及投资决策的问题，应提示用户咨询持牌投资顾问，并说明本系统仅提供资料查询",
    ),
    # 检索不到时的提示：不能笼统说"没找到资料"，
    # 否则用户会以为"这家公司没有财报"，而实际可能是知识库没收录
    no_hit_message="在现有知识库中没有找到相关的财经数据或报告",
    # ---------- 界面文案 ----------
    app_title="财经数据知识库问答系统",
    login_slogan="把财报、研究报告、行业数据交给它，用自然语言提问，得到注明出处的答案",
    welcome_title="财经数据知识库问答",
    welcome_hint="点击左侧「新对话」开始提问。系统会依据知识库中的财报与数据作答，并标注来源与报告期。",
    greet_message=(
        "您好！我是本企业知识库问答助手，可以帮您查询财经数据与报告"
        "（如财报指标、行业数据、公告摘要等）。请直接告诉我您想了解什么，"
        "我会从知识库中查找并给出带引用出处的回答。"
    ),
    whoami_message=(
        "我是财经数据知识库问答助手，专门回答知识库里的财报与数据问题。"
        "我只提供资料查询与数据呈现，不构成投资建议。您想问什么？"
    ),
    example_questions=(
        "海联银行去年的净利润是多少",
        "启明科技的毛利率怎么样",
        "长风能源的资产负债率",
    ),

    # ---------- 答案质量与范围（财经领域：最严格的档位）----------
    #
    # 财经答错代价高（可能被当成投资依据），所以：
    #   · 自检 2 次，不合格就打回重做
    #   · 绝不编造数字
    #   · 明确拒答超出范围的问题
    answer_verify_rounds=2,
    scope_description=(
        "本知识库收录财报数据、财务指标、行业研究、监管公告。"
        "可以回答：具体公司的财务数据、指标含义、报告期对比。"
        "不能回答：实时行情、股价预测、买卖建议、与资料无关的实时信息。"
    ),
    out_of_scope_message=(
        "这个问题超出了本知识库的收录范围。"
        "我只能回答知识库中的财报数据与财务指标，"
        "不能提供实时行情、投资建议或与资料无关的信息。"
    ),
    allow_external_facts=False,
    external_fact_hint=(
        "我无法获取实时行情或实时数据（这需要接入行情服务）。"
    ),
    open_intent_keywords=OPEN_INTENT_KEYWORDS,
    specific_hints=SPECIFIC_HINTS,
    # 别的领域的典型词：财经库里出现这些说明问错了库
    foreign_hints=(
        # 电商
        "商品", "商品信息", "本商品", "手机", "耳机", "手表", "型号", "参数",
        "保修", "售后", "快递", "发货", "下单",
        # 医疗
        "症状", "诊断", "用药", "处方", "病历",
        # 法律
        "法条", "判决", "起诉", "赔偿",
    ),
)
