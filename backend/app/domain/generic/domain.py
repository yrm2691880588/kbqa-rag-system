"""通用领域（兜底）。

## 什么时候用它

- 开发/测试时没有设置 `DOMAIN` 环境变量
- 用户新建的知识库暂时不属于任何特定行业

## 它和具体领域的差别

具体领域（电商/财经）有明确的行业身份和词表；通用领域**刻意保持中性**：

- 身份只说是「知识库问答助手」，不限定行业
- 列举意图词用泛化说法（「有哪些内容」「全部资料」）
- 具体提示词**不列任何行业名词**，避免误伤

## 为什么需要它

如果没有兜底领域，未设置 `DOMAIN` 时程序只能报错退出。
开发时频繁改环境变量很烦，而且 CI 里跑通用测试也需要一个能加载的领域。

注意：`APP_ENV=prod` 生产环境下 Core 会**强制要求**显式设置 DOMAIN，
不允许悄悄用通用领域 —— 那样上线后提示词会变得很泛，回答质量下降且没人察觉。
"""

from __future__ import annotations

from app.domain.base import DomainSpec

# 泛化的列举意图词：不绑定任何行业
OPEN_INTENT_KEYWORDS: tuple[str, ...] = (
    "介绍一下", "介绍下", "介绍一下内容",
    "有哪些内容", "有什么内容", "全部内容", "所有内容",
    "内容列表", "资料列表", "全部资料", "所有资料",
    "有哪些资料", "有什么资料", "你能介绍", "给我介绍",
    "给我说说", "你们有什么", "你们有哪些",
)

# 泛化的具体对象词：命中说明用户在问具体的东西
# 这里只放「明确的疑问指向」，不放行业名词（通用领域不知道用户是哪个行业）
SPECIFIC_HINTS: tuple[str, ...] = (
    "价格", "多少钱", "参数", "配置", "规格",
    "怎么用", "如何", "为什么", "区别", "对比",
)

spec = DomainSpec(
    name="generic",
    display_name="通用",
    persona="你是知识库问答助手",
    audience="普通用户",
    forbidden=(
        "不要编造答案，不要使用任何知识库之外的资料",
    ),
    no_hit_message="在现有知识库中没有找到相关资料",
    # ---------- 界面文案（中性表述，不绑定行业）----------
    app_title="知识库问答系统",
    login_slogan="把文档交给它，用自然语言提问，得到带出处的答案",
    welcome_title="知识库智能问答",
    welcome_hint="点击左侧「新对话」开始提问。AI 将依据知识库资料回答，并标注引用来源。",
    example_questions=(),
    open_intent_keywords=OPEN_INTENT_KEYWORDS,
    specific_hints=SPECIFIC_HINTS,
    # 通用领域不知道用户是什么行业，但电商/财经是最常见的两类，
    # 填进去能挡住大部分跨领域误判。
    foreign_hints=(
        # 电商
        "商品", "本商品", "手机", "耳机", "手表", "保修", "售后",
        # 财经
        "股票", "基金", "市盈率", "股价", "财报", "投资",
    ),
)
